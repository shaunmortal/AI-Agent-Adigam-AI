const probCorrect = (skill, difficulty) => 0.25 + 0.75 / (1 + Math.exp(-((skill - 0.5) * 7 - (difficulty - 3) * 0.6)));

// Port of server/internal/learner/mastery.go (ComputeMastery over SummariseAttempts).
function mastery(attemptsNewestFirst) {
  const n = attemptsNewestFirst.length;
  const buckets = { easy: [0, 0], medium: [0, 0], hard: [0, 0] };
  let correct = 0, recentCorrect = 0, streak = 0, streakOpen = true;
  attemptsNewestFirst.forEach((a, i) => {
    const b = buckets[a.difficulty];
    b[0]++;
    if (a.correct) {
      correct++;
      b[1]++;
      if (i < 10) recentCorrect++;
    }
    if (streakOpen && a.correct) streak++;
    else streakOpen = false;
  });
  const recentN = Math.min(n, 10);
  const weights = { easy: 1, medium: 2, hard: 3 };
  let ws = 0, tw = 0, level = 0, count = 0;
  for (const [k, [att, cor]] of Object.entries(buckets)) {
    if (!att) continue;
    ws += weights[k] * (cor / att);
    tw += weights[k];
    level += weights[k] * att;
    count += att;
  }
  const difficulty = tw ? (ws / tw) * (0.6 + 0.4 * (level / (count * 3))) : null;
  const parts = [[recentN ? recentCorrect / recentN : null, 0.4], [n ? correct / n : null, 0.25], [difficulty, 0.25], [clamp(streak / 5, 0, 1), 0.1]];
  let used = 0, sum = 0;
  for (const [v, w] of parts) if (v !== null) { used += w; sum += w * v; }
  const raw = used ? sum / used : 0.35;
  const confidence = n / (n + 5);
  const idleDays = attemptsNewestFirst[0].agoSecs / DAY;
  const decay = 1 - clamp(idleDays / 30, 0, 1) * 0.15;
  return {
    score: round2(clamp((raw * confidence + 0.35 * (1 - confidence)) * decay * 100, 0, 100)),
    total: n, correct, recentN, recentCorrect, buckets, streak,
    lastAttemptAgo: attemptsNewestFirst[0].agoSecs,
    lastCorrectAgo: attemptsNewestFirst.find((a) => a.correct)?.agoSecs ?? null,
  };
}

// Port of updateRevisionSchedule / FirstSchedule / NextReview (no exam date), one step per day.
function revision(attemptsOldestFirst) {
  const byDay = new Map();
  for (const a of attemptsOldestFirst) {
    const d = Math.floor(a.agoSecs / DAY);
    byDay.set(d, [...(byDay.get(d) ?? []), a]);
  }
  let s = null;
  for (const [day, list] of [...byDay].sort((x, y) => y[0] - x[0])) {
    const acc = (list.filter((a) => a.correct).length / list.length) * 100;
    if (!s && list.length <= 1) {
      s = { interval: 1, ease: 2.5, reviews: 0, lapses: 0, day, acc: null };
      continue;
    }
    const cur = s ?? { interval: 1, ease: 2.5, reviews: 0, lapses: 0 };
    const reviews = cur.reviews + 1;
    let { ease, lapses } = cur;
    let interval;
    if (acc < 50) { interval = 1; ease = clamp(ease - 0.15, 1.3, 3); lapses++; }
    else if (acc >= 80) {
      if (list.length < 3) interval = Math.floor(cur.interval * 1.2 + 0.5);
      else if (reviews === 1) interval = 3;
      else { interval = Math.floor(cur.interval * cur.ease + 0.5); ease = clamp(ease + 0.15, 1.3, 3); }
    } else interval = Math.floor(cur.interval * 1.2 + 0.5);
    s = { interval: clamp(interval, 1, 60), ease: round2(ease), reviews, lapses, day, acc: round2(acc) };
  }
  return s;
}

function simulate(index) {
  const holds = new Set(CLASS_WIDE.filter(([, p]) => rand() < p).map(([id]) => id));
  for (let i = 0; i < 2; i++) holds.add(pickOne(MISCONCEPTIONS).id);
  const startedWith = [...holds];
  const talent = gauss() * 0.12;
  const skill = new Map(CONCEPTS.map((c) => {
    const held = MISCONCEPTIONS.some((m) => m.concept === c.id && holds.has(m.id));
    const base = CHAPTER_SKILL[c.chapter] + talent + gauss() * 0.12;
    return [c.id, clamp(held ? Math.min(base, 0.35) : base, 0.05, 0.97)];
  }));
  const attempts = [];
  const seen = new Set();

  const answer = (q, agoSecs, source) => {
    const heldIdx = q.options.findIndex((o) => o.misconception && holds.has(o.misconception));
    const heldInConcept = MISCONCEPTIONS.find((m) => m.concept === q.concept && holds.has(m.id));
    let chosen, verdict, reasoning, mc = null;
    if (heldIdx >= 0 && rand() < 0.8) {
      chosen = heldIdx; mc = q.options[heldIdx].misconception; verdict = "flawed";
      reasoning = pickOne(mcById.get(mc).examples);
    } else if (rand() < probCorrect(skill.get(q.concept), q.difficulty)) {
      chosen = q.answer;
      if (heldInConcept && rand() < 0.3) {
        verdict = "flawed"; mc = heldInConcept.id; reasoning = pickOne(heldInConcept.examples);
      } else if (rand() < 0.75) {
        verdict = "sound";
        reasoning = `because ${q.explanation.split(". ")[0].replace(/^./, (c) => c.toLowerCase()).replace(/\.$/, "")}`;
      } else {
        verdict = "missing"; reasoning = null;
      }
    } else {
      chosen = pickOne(q.options.map((_, i) => i).filter((i) => i !== q.answer));
      verdict = "missing"; reasoning = rand() < 0.5 ? "not sure" : null;
      mc = q.options[chosen].misconception;
    }
    const correct = chosen === q.answer;
    attempts.push({
      id: uid(`attempt:${index}:${attempts.length}`), q, chosen, correct, verdict, reasoning,
      mc: correct && verdict !== "flawed" ? null : mc, agoSecs, source,
      difficulty: difficultyLabel(q.difficulty), seconds: 20 + Math.floor(rand() * 100),
    });
    seen.add(q.id);
    if (source === "practice") {
      const s = skill.get(q.concept);
      skill.set(q.concept, s + 0.06 * (1 - s));
      if (mc && rand() < 0.2) holds.delete(mc);
    }
  };

  // The diagnostic: one question per topic, covering this student's class-wide misconceptions.
  const start = (8 + rand() * 2) * DAY;
  const mustCover = CLASS_WIDE.map(([mc]) => mc).filter((mc) => holds.has(mc)).map((mc) => mcById.get(mc).concept);
  const rest = shuffle(CONCEPTS.map((c) => c.id).filter((id) => !mustCover.includes(id)));
  [...mustCover, ...rest].slice(0, DIAGNOSTIC_SIZE).forEach((conceptId, i) => {
    const pool = BANK.filter((q) => q.concept === conceptId);
    const exposing = pool.find((q) => q.options.some((o) => o.misconception && holds.has(o.misconception)));
    answer(exposing ?? pool.find((q) => q.difficulty === 3) ?? pool[0], start - i * 75, "assessment");
  });

  // Practice: weakest concept whose prerequisites are in place, at a difficulty to match. Like a
  // real student, each one works mostly through two chapters, so those topics build enough
  // evidence for the app's mastery formula to move well away from its 35% prior.
  const lastActive = rand() < 0.25 ? (3 + rand() * 3) * DAY : rand() * 0.8 * DAY;
  const focus = new Set(shuffle(CHAPTERS.map((ch) => ch.id)).slice(0, 2));
  const count = 60 + Math.floor(rand() * 50);
  for (let i = 0; i < count; i++) {
    const at = Math.max(60, start - DAY - ((start - DAY - lastActive) * (i + rand() * 0.5)) / count);
    const m = (id) => {
      const list = attempts.filter((a) => a.q.concept === id);
      return list.length ? list.filter((a) => a.correct).length / list.length : 0.35;
    };
    const inFocus = CONCEPTS.filter((c) => focus.has(c.chapter) || rand() < 0.1);
    const ready = inFocus.filter((c) => c.prereqs.every((p) => m(p) >= 0.5));
    const target = [...(ready.length ? ready : CONCEPTS)].sort((a, b) => m(a.id) - m(b.id) + (rand() - 0.5) * 0.3)[0];
    const want = m(target.id) < 0.4 ? 2 : m(target.id) < 0.7 ? 3 : 4;
    const pool = BANK.filter((q) => q.concept === target.id);
    const fresh = pool.filter((q) => !seen.has(q.id));
    const q = [...(fresh.length ? fresh : pool)].sort((a, b) => Math.abs(a.difficulty - want) - Math.abs(b.difficulty - want))[0];
    answer(q, at, "practice");
  }
  return { attempts, holds: startedWith };
}

